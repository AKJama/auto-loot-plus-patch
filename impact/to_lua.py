"""Converts an assembled impact program descriptor (JSON) into a Lua module for the EML data mod."""
import json, sys

def lua(v, ind=0):
    pad = '  ' * ind
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list):
        if all(isinstance(x, int) for x in v):
            return '{' + ','.join(str(x) for x in v) + '}'
        return '{\n' + ''.join(pad + '  ' + lua(x, ind + 1) + ',\n' for x in v) + pad + '}'
    if isinstance(v, dict):
        return '{\n' + ''.join(f'{pad}  {k} = {lua(x, ind + 1)},\n' for k, x in v.items() if not k.startswith('$')) + pad + '}'
    raise TypeError(type(v))

src, dst = sys.argv[1], sys.argv[2]
d = json.load(open(src, encoding='utf-8'))
with open(dst, 'w', encoding='utf-8') as f:
    f.write('-- Generated by impact/to_lua.py from the assembled autosmash program. Do not edit by hand.\n')
    f.write('return ' + lua(d) + '\n')
